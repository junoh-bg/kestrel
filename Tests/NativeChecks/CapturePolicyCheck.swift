import Foundation

@main struct CapturePolicyCheck {
  static func main() {
    var failures = [String]()
    func check(_ condition: Bool, _ message: String) { if !condition { failures.append(message) } }
    check(
      !CapturePolicy.allows(types: ["public.utf8-plain-text"], source: nil, enabled: false),
      "paused capture must reject plain text")
    check(
      CapturePolicy.allows(types: ["public.utf8-plain-text"], source: nil, enabled: true),
      "enabled capture must allow ordinary text")
    for type in [
      "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
      "org.nspasteboard.AutoGeneratedType",
    ] {
      check(
        !CapturePolicy.allows(types: [type, "public.utf8-plain-text"], source: nil, enabled: true),
        "must reject sensitive type \(type)")
    }
    for source in [
      "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop",
      "com.apple.keychainaccess",
    ] {
      check(
        !CapturePolicy.allows(types: ["public.utf8-plain-text"], source: source, enabled: true),
        "must reject password manager \(source)")
    }
    if failures.isEmpty {
      print("Capture policy: 9 checks passed")
    } else {
      for failure in failures { print("FAIL: \(failure)") }
      exit(1)
    }
  }
}
