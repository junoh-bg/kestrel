import Foundation

// Pasteboard conventions are hints, not a guarantee that ordinary text is non-sensitive.
enum CapturePolicy {
  static func allows(types: Set<String>, source: String?, enabled: Bool) -> Bool {
    guard enabled else { return false }
    let blocked = ["concealed", "transient", "autogenerated"]
    guard !types.contains(where: { type in blocked.contains { type.lowercased().contains($0) } })
    else { return false }
    let source = source?.lowercased() ?? ""
    return ![
      "1password", "onepassword", "bitwarden", "keychainaccess", "securityagent", "keepass",
      "lastpass", "dashlane",
    ].contains { source.contains($0) }
  }
}
